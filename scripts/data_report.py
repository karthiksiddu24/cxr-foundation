#!/usr/bin/env python3
"""Generate docs/data_report.md (+ figures) from the processed NIH index. No hand-typed numbers.

Usage: uv run scripts/data_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import polars as pl

from cxr_common.labels import DISPLAY_NAMES, NIH_LABELS
from cxr_ml.data.nih import check_no_patient_leakage
from cxr_ml.paths import DataPaths
from cxr_ml.viz import style

REPO = Path(__file__).resolve().parents[1]
DOCS = REPO / "docs"
FIG = DOCS / "figures"
SPLITS = ("train", "val", "test")


def pct(x: float) -> str:
    return f"{100 * x:.2f}%"


def main() -> None:
    style.apply()
    paths = DataPaths.from_env()
    df = pl.read_parquet(paths.index("nih"))
    meta = json.loads((paths.processed("nih") / "splits.json").read_text())
    patients = check_no_patient_leakage(df)
    FIG.mkdir(parents=True, exist_ok=True)

    # ---- prevalence table + figure
    prev = {
        s: df.filter(pl.col("split") == s).select(list(NIH_LABELS)).mean().row(0) for s in SPLITS
    }
    pos = {s: df.filter(pl.col("split") == s).select(list(NIH_LABELS)).sum().row(0) for s in SPLITS}
    order = np.argsort(prev["train"])  # ascending -> largest at top in barh
    fig, ax = plt.subplots(figsize=(7, 6))
    h = 0.26
    for i, s in enumerate(SPLITS):
        y = np.arange(len(NIH_LABELS)) + (1 - i) * h
        ax.barh(
            y,
            [100 * prev[s][k] for k in order],
            height=h - 0.03,
            color=style.SPLIT_COLORS[s],
            label=s,
        )
    ax.set_yticks(np.arange(len(NIH_LABELS)), [DISPLAY_NAMES[NIH_LABELS[k]] for k in order])
    ax.set_xlabel("Images with finding (%)")
    ax.set_title("Label prevalence by split (NIH ChestX-ray14)")
    ax.grid(axis="y", visible=False)
    ax.legend(loc="lower right")
    fig.savefig(FIG / "nih_prevalence.png")
    plt.close(fig)

    # ---- images per patient
    ipp = df.group_by("patient_id").len()["len"].to_numpy()
    fig, ax = plt.subplots(figsize=(7, 3))
    bins = np.arange(1, min(ipp.max(), 60) + 2) - 0.5
    ax.hist(np.clip(ipp, 1, 60), bins=bins, color=style.SERIES[0], rwidth=0.85)
    ax.set_yscale("log")
    ax.set_xlabel("Images per patient (clipped at 60)")
    ax.set_ylabel("Patients (log)")
    ax.set_title("Images per patient")
    fig.savefig(FIG / "nih_images_per_patient.png")
    plt.close(fig)

    # ---- tabular stats
    lines: list[str] = []
    w = lines.append
    w("# NIH ChestX-ray14 — dataset report\n")
    w("_Generated by `scripts/data_report.py` from `index.parquet`; do not edit by hand._\n")
    w(f"Source: `{meta['source'][0]}` @ `{meta['source'][1].split('=')[1][:12]}`  ")
    w(
        f"Split seed: {meta['split_seed']} · val fraction of train_val patients: {meta['val_frac']}  "
    )
    w(f"Split digest: `{meta['split_digest']}` · index digest: `{meta['index_digest']}`\n")
    w("## Splits\n")
    w("| Split | Images | Patients | Images/patient (mean) | No finding |")
    w("|---|---:|---:|---:|---:|")
    for s in SPLITS:
        d = df.filter(pl.col("split") == s)
        nf = (d.select(list(NIH_LABELS)).sum_horizontal() == 0).mean()
        w(
            f"| {s} | {d.height:,} | {patients[s]:,} | {d.height / patients[s]:.2f} | {pct(float(nf))} |"
        )
    w("\nPatient leakage check: **passed** (no patient appears in more than one split).\n")
    w("Label-fraction subsets (patient-level, nested, drawn from train):\n")
    w("| Fraction | Images | Patients |")
    w("|---|---:|---:|")
    for f, v in meta["fractions"].items():
        w(f"| {float(f):.0%} | {v['images']:,} | {v['patients']:,} |")
    w(f"| 100% | {df.filter(pl.col('split') == 'train').height:,} | {patients['train']:,} |")

    w("\n## Class prevalence\n")
    w("![prevalence](figures/nih_prevalence.png)\n")
    f1 = df.filter(pl.col("in_frac_0p01"))
    f10 = df.filter(pl.col("in_frac_0p1"))
    w("| Finding | Train | Val | Test | Positives in 1% subset | Positives in 10% subset |")
    w("|---|---:|---:|---:|---:|---:|")
    for k, n in enumerate(NIH_LABELS):
        w(
            f"| {DISPLAY_NAMES[n]} | {pct(prev['train'][k])} ({pos['train'][k]:,}) | "
            f"{pct(prev['val'][k])} ({pos['val'][k]:,}) | {pct(prev['test'][k])} ({pos['test'][k]:,}) | "
            f"{int(f1[n].sum())} | {int(f10[n].sum())} |"
        )
    tr = df.filter(pl.col("split") == "train")
    te = df.filter(pl.col("split") == "test")
    w(
        f"\nNote: the official test list differs from train/val: higher prevalence for most "
        f"findings and {te.height / patients['test']:.1f} images per patient vs "
        f"{tr.height / patients['train']:.1f} in train (more follow-up studies per patient). AUROC "
        "is prevalence-invariant; AUPRC is not, so AUPRC should not be compared across splits.\n"
    )
    rare = [DISPLAY_NAMES[n] for n in NIH_LABELS if int(f1[n].sum()) < 10]
    if rare:
        w(
            f"Findings with fewer than 10 positives in the 1% subset: {', '.join(rare)}. "
            "Results for these in the 1% setting are dominated by noise.\n"
        )

    w("## Images per patient\n")
    w("![images per patient](figures/nih_images_per_patient.png)\n")
    q = np.percentile(ipp, [50, 90, 99])
    w(
        f"Median {q[0]:.0f}, 90th percentile {q[1]:.0f}, 99th percentile {q[2]:.0f}, max {ipp.max()}. "
        "Because some patients contribute dozens of images, confidence intervals resample patients, "
        "not images.\n"
    )

    w("## View position, sex, age\n")
    w("| Split | PA | AP | Female | Male | Age median (IQR) |")
    w("|---|---:|---:|---:|---:|---|")
    for s in SPLITS:
        d = df.filter(pl.col("split") == s)
        a = d.filter(pl.col("age") <= 120)["age"].to_numpy()
        q1, med, q3 = np.percentile(a, [25, 50, 75])
        w(
            f"| {s} | {pct(float((d['view'] == 'PA').mean()))} | {pct(float((d['view'] == 'AP').mean()))} | "
            f"{pct(float((d['sex'] == 'F').mean()))} | {pct(float((d['sex'] == 'M').mean()))} | "
            f"{med:.0f} ({q1:.0f}–{q3:.0f}) |"
        )
    bad_age = int((df["age"] > 120).sum())
    if bad_age:
        w(
            f"\n{bad_age} images have recorded ages above 120 (data-entry errors); they are excluded "
            "from the age summary only.\n"
        )
    w(
        f"\nThe test split is {pct(float((te['view'] == 'AP').mean()))} AP vs "
        f"{pct(float((tr['view'] == 'AP').mean()))} in train. AP films are typically portable "
        "bedside studies of sicker patients, so view position is a plausible confounder; RESULTS.md "
        "reports performance stratified by view.\n"
    )
    w("## Known label caveats\n")
    w(
        "- Labels were mined from radiology reports with NLP, not read from the images; the dataset "
        "authors report imperfect accuracy, and independent re-reads found substantial label noise "
        "for some classes. Test-set AUROC therefore measures agreement with noisy report-derived "
        "labels.\n- *Infiltration* is a vague, inconsistently used term."
    )
    (DOCS / "data_report.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {DOCS / 'data_report.md'}")


if __name__ == "__main__":
    main()
