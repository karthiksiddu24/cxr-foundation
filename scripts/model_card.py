#!/usr/bin/env python3
"""Render docs/MODEL_CARD.md from the deployed bundle's manifest (no hand-typed numbers).

    uv run scripts/model_card.py [bundle_dir=$CXR_DATA_ROOT/artifacts/bundles/current]

The app shows the same manifest live at /model; this file is the static copy for GitHub.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

from cxr_common.bundle import Manifest
from cxr_ml.paths import DataPaths

REPO = Path(__file__).resolve().parents[1]


def iv(x: Any) -> str:
    return "—" if x is None else f"{x.point:.3f} ({x.ci_low:.3f}–{x.ci_high:.3f})"


def main() -> None:
    bdir = (
        Path(sys.argv[1])
        if len(sys.argv) > 1
        else DataPaths.from_env().root / "artifacts" / "bundles" / "current"
    )
    m = Manifest.model_validate_json((bdir / "manifest.json").read_text())
    c, p = m.card, m.provenance
    w: list[str] = []
    add = w.append
    add(f"# Model card: `{m.model_id}` v{m.version}\n")
    add(
        "_Generated by `scripts/model_card.py` from the deployed bundle's `manifest.json`; the "
        "running app shows the same card at `/model`._\n"
    )
    add("> Research demonstration only. Not a medical device. Not for clinical use.\n")
    if m.placeholder:
        add("> **UNTRAINED PLACEHOLDER BUNDLE: scores are meaningless.**\n")
    add("## Model\n")
    add("| | |\n|---|---|")
    add(f"| Architecture | `{m.arch}`, initialization `{m.init}` |")
    add(f"| Input | 1×{m.input_size}×{m.input_size} grayscale, letterboxed, values in [0, 1] |")
    add(f"| Outputs | 14 finding scores + {m.heatmap_grid[0]}×{m.heatmap_grid[1]} heatmap each |")
    add(f"| Runtime | ONNX opset {m.opset} (`sha256 {m.onnx_sha256[:16]}…`) |")
    add(
        f"| Out-of-distribution check | {m.ood.method}, {m.ood.feature_dim}-d features, "
        f"flag above the {m.ood.threshold_quantile:.1%} validation quantile |"
    )
    add(
        f"| Provenance | run `{p.run}`, commit `{(p.git_commit or '')[:10]}`, "
        f"split digest `{p.split_digest}`, built {p.created_at} |\n"
    )
    add("## Intended use\n")
    add(c.intended_use + "\n")
    add("**Not intended for:**\n")
    w.extend(f"- {x}" for x in c.not_intended_for)
    add("")
    add("## Data\n")
    add(f"- **Training:** {c.training_data}")
    add(f"- **Evaluation:** {c.evaluation_data}\n")
    add("## Performance (NIH official test set)\n")
    add(
        f"Mean AUROC over 14 findings: **{iv(c.mean_test_auroc)}** (patient-level bootstrap 95% CI)."
    )
    if c.mean_ece_raw is not None and c.mean_ece_calibrated is not None:
        add(
            f"Mean expected calibration error: {c.mean_ece_raw:.3f} before, "
            f"{c.mean_ece_calibrated:.3f} after per-finding temperature scaling.\n"
        )
    add(
        "| Finding | Test AUROC (95% CI) | Test AUPRC (95% CI) | Prevalence | Threshold "
        "| Test sens. | Test spec. |"
    )
    add("|---|---:|---:|---:|---:|---:|---:|")
    for f in m.findings:
        t = f.threshold
        prev = "—" if f.test_prevalence is None else f"{f.test_prevalence:.1%}"
        sens = "—" if t.test_sensitivity is None else f"{t.test_sensitivity:.2f}"
        spec = "—" if t.test_specificity is None else f"{t.test_specificity:.2f}"
        add(
            f"| {f.display_name} | {iv(f.test_auroc)} | {iv(f.test_auprc)} | {prev} | "
            f"{t.threshold:.3f} | {sens} | {spec} |"
        )
    add(
        "\nThresholds maximize Youden's J on the validation split; test sensitivity and "
        "specificity show how they transfer.\n"
    )
    if c.external:
        add("## External validation\n")
        for e in c.external:
            add(
                f"**{e.dataset}**, {e.split} split, {e.n_images} images: mean AUROC {iv(e.mean_auroc)}."
            )
            if e.notes:
                add(f"{e.notes}\n")
            add("| Finding | AUROC (95% CI) |\n|---|---:|")
            w.extend(f"| {k} | {iv(v)} |" for k, v in e.per_finding.items())
            add("")
    add("## Limitations\n")
    w.extend(f"- {x}" for x in c.limitations)
    add(
        "\nFull evaluation, including heatmap localization and the shortcut audit: [RESULTS.md](../RESULTS.md)."
    )
    out = REPO / "docs" / "MODEL_CARD.md"
    out.write_text("\n".join(w) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
